-- SSH 服务器管理（与 T2 无关联）
-- 设计说明见 doc/SSH服务器管理设计.md
-- 实现 M1 时加入 app.database.init.scripts

CREATE TABLE IF NOT EXISTS ssh_group (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  parent_id BIGINT DEFAULT NULL COMMENT 'NULL=根分组',
  name VARCHAR(128) NOT NULL COMMENT '同级唯一（应用层校验）',
  remark VARCHAR(512) DEFAULT NULL COMMENT '分组备注',
  sort_order INT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_ssh_group_parent (parent_id),
  CONSTRAINT fk_ssh_group_parent FOREIGN KEY (parent_id) REFERENCES ssh_group (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='SSH资产-多级分组';

CREATE TABLE IF NOT EXISTS ssh_host (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  group_id BIGINT NOT NULL,
  name VARCHAR(128) NOT NULL COMMENT '展示名',
  host VARCHAR(255) NOT NULL COMMENT 'IP或域名',
  port INT NOT NULL DEFAULT 22,
  remark VARCHAR(512) DEFAULT NULL COMMENT '主机/连接备注',
  sort_order INT NOT NULL DEFAULT 0,
  enabled TINYINT NOT NULL DEFAULT 1 COMMENT '0=禁止新建连接',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_ssh_host_group (group_id),
  CONSTRAINT fk_ssh_host_group FOREIGN KEY (group_id) REFERENCES ssh_group (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='SSH资产-主机';

CREATE TABLE IF NOT EXISTS ssh_account (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  host_id BIGINT NOT NULL,
  username VARCHAR(64) NOT NULL,
  auth_type VARCHAR(32) NOT NULL COMMENT 'PASSWORD|PRIVATE_KEY|PRIVATE_KEY_WITH_PASSPHRASE',
  secret_enc VARBINARY(8192) NOT NULL COMMENT 'AES-GCM加密JSON',
  secret_hint VARCHAR(64) DEFAULT NULL,
  default_cwd VARCHAR(512) DEFAULT NULL,
  remark VARCHAR(512) DEFAULT NULL COMMENT '账户/登录备注',
  sort_order INT NOT NULL DEFAULT 0,
  enabled TINYINT NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_ssh_account_host_user (host_id, username),
  KEY idx_ssh_account_host (host_id),
  CONSTRAINT fk_ssh_account_host FOREIGN KEY (host_id) REFERENCES ssh_host (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='SSH资产-登录账户';
